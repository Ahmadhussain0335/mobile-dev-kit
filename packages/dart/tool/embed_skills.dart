// Generates lib/src/skills_data.g.dart from the repository's skills/ folder.
//
// `dart install` AOT-compiles the CLI, so the skills cannot be read from
// package files at runtime and are embedded as string constants instead.
//
// Usage (from packages/dart):
//   dart run tool/embed_skills.dart          # regenerate
//   dart run tool/embed_skills.dart --check  # exit 1 if the file is stale

import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;
import 'package:yaml/yaml.dart';

final packageRoot = p.dirname(p.dirname(p.fromUri(Platform.script)));
final skillsRoot = p.normalize(p.join(packageRoot, '..', '..', 'skills'));
final outputPath = p.join(packageRoot, 'lib', 'src', 'skills_data.g.dart');

Future<void> main(List<String> args) async {
  final check = args.contains('--check');
  if (!Directory(skillsRoot).existsSync()) {
    stderr.writeln('Skills folder not found: $skillsRoot');
    exit(2);
  }

  final generated = await format(generate());

  if (check) {
    final output = File(outputPath);
    final current = output.existsSync() ? output.readAsStringSync() : '';
    if (current != generated) {
      stderr.writeln(
        '${p.relative(outputPath, from: packageRoot)} is stale. '
        'Run: dart run tool/embed_skills.dart',
      );
      exit(1);
    }
    stdout.writeln('Embedded skills are up to date.');
    return;
  }

  File(outputPath).writeAsStringSync(generated);
  stdout.writeln('Wrote ${p.relative(outputPath, from: packageRoot)}.');
}

String generate() {
  final skillDirs = Directory(skillsRoot)
      .listSync()
      .whereType<Directory>()
      .where((d) => File(p.join(d.path, 'SKILL.md')).existsSync())
      .toList()
    ..sort((a, b) => a.path.compareTo(b.path));

  final files = StringBuffer();
  final descriptions = StringBuffer();

  for (final dir in skillDirs) {
    final name = p.basename(dir.path);
    final entries = dir
        .listSync(recursive: true)
        .whereType<File>()
        .where((f) => !p.basename(f.path).startsWith('.'))
        .map(
            (f) => p.posix.joinAll(p.split(p.relative(f.path, from: dir.path))))
        .toList()
      ..sort();

    files.writeln('  ${literal(name)}: {');
    for (final rel in entries) {
      final content = readNormalized(p.join(dir.path, rel));
      files.writeln('    ${literal(rel)}: ${literal(content)},');
    }
    files.writeln('  },');

    final skillText = readNormalized(p.join(dir.path, 'SKILL.md'));
    descriptions.writeln(
      '  ${literal(name)}: ${literal(frontmatterDescription(skillText))},',
    );
  }

  return '''
// GENERATED CODE - DO NOT MODIFY BY HAND.
// Generated by tool/embed_skills.dart from the repository skills/ folder.

// ignore_for_file: prefer_single_quotes

/// Skill name -> file path inside the skill folder -> file content.
const Map<String, Map<String, String>> embeddedSkillFiles = {
$files};

/// Skill name -> description from the SKILL.md frontmatter.
const Map<String, String> embeddedSkillDescriptions = {
$descriptions};
''';
}

/// Reads a text file with line endings normalized to LF, so a Windows
/// checkout produces the same output.
String readNormalized(String path) =>
    File(path).readAsStringSync().replaceAll('\r\n', '\n');

String frontmatterDescription(String skillText) {
  final end = skillText.indexOf('\n---\n', 4);
  final yaml = loadYaml(skillText.substring(4, end)) as YamlMap;
  return (yaml['description'] as String).trim();
}

/// A Dart string literal for [value]. JSON escaping covers quotes,
/// backslashes and control characters; `$` must also be escaped for Dart.
String literal(String value) => jsonEncode(value).replaceAll(r'$', r'\$');

Future<String> format(String source) async {
  final temp = await Directory.systemTemp.createTemp('embed_skills');
  try {
    final file = File(p.join(temp.path, 'skills_data.g.dart'))
      ..writeAsStringSync(source);
    final result = await Process.run(Platform.resolvedExecutable, [
      'format',
      '--language-version=3.5',
      file.path,
    ]);
    if (result.exitCode != 0) {
      throw StateError('dart format failed: ${result.stderr}');
    }
    return file.readAsStringSync();
  } finally {
    await temp.delete(recursive: true);
  }
}
